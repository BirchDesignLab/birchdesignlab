/** Probe: which pointer events does a CDP touch drag on a colour bar produce? node w1-t5-probe-touch.mjs [width] */
import { chromium } from 'playwright';
import { serveDist } from '../lib/serve-dist.mjs';
import { suppressPrompt } from '../lib/portal-prompt.mjs';
const w = +(process.argv[2] || 390);
const server = await serveDist(4470);
const browser = await chromium.launch({ args: ['--use-angle=d3d11', '--enable-gpu', '--ignore-gpu-blocklist'] });
const ctx = await browser.newContext({ viewport: { width: w, height: 1250 }, isMobile: true, hasTouch: true, reducedMotion: 'no-preference' });
await suppressPrompt(ctx);
const page = await ctx.newPage();
const cdp = await ctx.newCDPSession(page);
await page.goto('http://127.0.0.1:4470/t/bauhaus/about/', { waitUntil: 'networkidle' });
await page.addStyleTag({ content: 'bdl-switcher{display:none!important}' });
await page.locator('[data-quiz]').scrollIntoViewIfNeeded();
await page.waitForTimeout(1500);
await page.evaluate(() => { window.__ev = []; for (const t of ['pointerdown', 'pointermove', 'pointerup', 'pointercancel', 'lostpointercapture', 'touchstart', 'touchmove', 'touchend', 'click']) document.addEventListener(t, (e) => window.__ev.push(t + ':' + (e.target.className?.baseVal ?? e.target.className) + ':' + Math.round(e.clientX ?? e.touches?.[0]?.clientX ?? -1)), true); });
const a = await page.locator('[data-pick="yellow"]').boundingBox();
const b = await page.locator('[data-shape="triangle"]').boundingBox();
const A = [a.x + a.width / 2, a.y + a.height / 2], B = [b.x + b.width / 2, b.y + b.height / 2];
const touch = (type, x, y) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: type === 'touchEnd' ? [] : [{ x, y, id: 1 }] });
await touch('touchStart', ...A);
for (let i = 1; i <= 8; i++) await touch('touchMove', A[0] + ((B[0] - A[0]) * i) / 8, A[1] + ((B[1] - A[1]) * i) / 8);
await touch('touchEnd');
await page.waitForTimeout(500);
console.log(await page.evaluate(() => window.__ev));
console.log(await page.evaluate(() => document.querySelector('[data-shape=triangle]').getAttribute('data-fill')));
await browser.close(); server.close(); process.exit(0);
