/**
 * Stage 4 Tier A proof a4: builds numerals.svg, the ten constructed digits.
 *
 * The module: one stroke S = 20. A digit cell is 3S wide and 5S tall
 * (viewBox 0 0 60 100). Four elements only, after Albers's standard
 * elements (Kombinationsschrift):
 *   bar   a rectangle, always S thick (vertical or horizontal)
 *   ring  a full circle ring: outer radius 1.5S (30), inner 0.5S (10)
 *   half  a half ring, same radii
 *   quad  a quarter ring, same radii
 * Rings sit on two centres only: (30,30) and (30,70). Two rings on those
 * centres overlap in one shared band (y 40 to 60), which is what lets 3, 5
 * and 8 close without a join to draw.
 *
 * Output: numerals.svg, one <symbol id="n0".."n9"> per digit, each element
 * its own <path class="el el-<kind>"> so Tier B can animate elements one by
 * one (a <use> shadow tree cannot be styled per element, so the component
 * inlines the paths and the sprite is the source of truth and the specimen).
 *
 * Run: node scripts/themes/proofs/stage4-bauhaus-numerals/build-numerals.mjs
 */
import { writeFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const R = 30, r = 10;
const n = (v) => +v.toFixed(3);
const pt = (cx, cy, a, rad) => [n(cx + rad * Math.cos((a * Math.PI) / 180)), n(cy + rad * Math.sin((a * Math.PI) / 180))];
const P = ([x, y]) => `${x} ${y}`;

const bar = (x, y, w, h) => ({ kind: 'bar', axis: w >= h ? 'h' : 'v', d: `M${x} ${y}h${w}v${h}h${-w}Z` });
/* ring: outer circle one way, inner the other; fill-rule evenodd anyway. */
const ring = (cx, cy) => ({
  kind: 'ring', cx, cy,
  d: `M${cx - R} ${cy}A${R} ${R} 0 1 0 ${cx + R} ${cy}A${R} ${R} 0 1 0 ${cx - R} ${cy}Z` +
     `M${cx - r} ${cy}A${r} ${r} 0 1 1 ${cx + r} ${cy}A${r} ${r} 0 1 1 ${cx - r} ${cy}Z`,
});
/* Sweep in screen angles (y down): 0 = right, 90 = down, 180 = left, 270 = up. */
const arc = (kind, cx, cy, a0, span) => {
  const a1 = a0 + span;
  const large = span > 180 ? 1 : 0;
  return {
    kind, cx, cy,
    d: `M${P(pt(cx, cy, a0, R))}A${R} ${R} 0 ${large} 1 ${P(pt(cx, cy, a1, R))}L${P(pt(cx, cy, a1, r))}A${r} ${r} 0 ${large} 0 ${P(pt(cx, cy, a0, r))}Z`,
  };
};
const half = (cx, cy, which) => arc('half', cx, cy, { upper: 180, lower: 0, left: 90, right: 270 }[which], 180);
const quad = (cx, cy, which) => arc('quad', cx, cy, { ur: 270, lr: 0, ll: 90, ul: 180 }[which], 90);

const DIGITS = {
  0: [half(30, 30, 'upper'), bar(0, 30, 20, 40), bar(40, 30, 20, 40), half(30, 70, 'lower')],
  1: [bar(40, 0, 20, 100), quad(40, 30, 'ul')],
  2: [half(30, 30, 'upper'), quad(30, 30, 'lr'), bar(0, 40, 30, 20), bar(0, 40, 20, 60), bar(0, 80, 60, 20)],
  3: [half(30, 30, 'upper'), quad(30, 30, 'lr'), quad(30, 70, 'ur'), half(30, 70, 'lower')],
  4: [bar(0, 0, 20, 60), bar(0, 40, 60, 20), bar(40, 0, 20, 100)],
  5: [bar(0, 0, 60, 20), bar(0, 0, 20, 60), bar(0, 40, 30, 20), quad(30, 70, 'ur'), half(30, 70, 'lower')],
  6: [quad(30, 30, 'ul'), bar(0, 30, 20, 40), ring(30, 70)],
  7: [bar(0, 0, 30, 20), quad(30, 30, 'ur'), bar(40, 30, 20, 70)],
  8: [ring(30, 30), ring(30, 70)],
  9: [ring(30, 30), bar(40, 30, 20, 40), quad(30, 70, 'lr')],
};

let svg = `<svg xmlns="http://www.w3.org/2000/svg" width="0" height="0" style="position:absolute" aria-hidden="true" focusable="false">\n`;
svg += `<!-- Constructed numerals, module S=20, cell 60x100. Generated by build-numerals.mjs; do not hand-edit. -->\n`;
for (const [digit, els] of Object.entries(DIGITS)) {
  svg += `<symbol id="n${digit}" viewBox="0 0 60 100">\n`;
  for (const e of els) {
    const extra = e.axis ? ` data-axis="${e.axis}"` : '';
    svg += `  <path class="el el-${e.kind}"${extra} fill-rule="evenodd" d="${e.d}"/>\n`;
  }
  svg += `</symbol>\n`;
}
svg += `</svg>\n`;
await writeFile(join(HERE, 'numerals.svg'), svg);
console.log(`numerals.svg: ${Object.keys(DIGITS).length} digits, ${Object.values(DIGITS).reduce((a, b) => a + b.length, 0)} elements`);
