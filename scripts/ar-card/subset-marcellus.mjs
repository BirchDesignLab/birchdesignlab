// Cuts a Latin-ASCII subset of Marcellus and writes it into
// src/lib/card-font.ts as a base64 woff2 string.
//
// Why the card landing needs its own copy of the font at all: that page is
// deliberately standalone (no BaseLayout, no site CSS, no @fontsource import),
// because it is the first thing a stranger sees after scanning a card and the
// whole document is meant to arrive in one round trip. Linking a font would
// cost a second request and a visible fallback flash on exactly the two lines
// that carry the brand. Inlining the subset costs neither.
//
// Full printable ASCII rather than just the glyphs the page happens to use
// today. An exact-text cut is about 3.7KB against 8.4KB here, but it turns
// every copy edit into a silent regression: change one word, get a generic
// serif for it and no error anywhere. 8.4KB is worth not owning that trap.
//
// Requires pyftsubset (`pip install fonttools brotli`). This is a generator,
// not a build step; it runs when the font or the reasoning above changes.
// Rerun with: node scripts/ar-card/subset-marcellus.mjs
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, unlinkSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';

const root = join(import.meta.dirname, '..', '..');
// The same pinned TTF the OG renderer uses, so the card, the OG cards and the
// outlined lockups are all cut from one file rather than three downloads.
const TTF = join(root, 'scripts', 'og', 'fonts', 'Marcellus-Regular.ttf');
const OUT = join(root, 'src', 'lib', 'card-font.ts');
const tmp = join(tmpdir(), `marcellus-card-${process.pid}.woff2`);

try {
  execFileSync(
    'pyftsubset',
    [
      TTF,
      `--output-file=${tmp}`,
      '--flavor=woff2',
      '--layout-features=kern',
      '--unicodes=U+0020-007E',
      '--no-hinting',
      '--desubroutinize',
    ],
    { stdio: ['ignore', 'inherit', 'inherit'] },
  );
} catch (err) {
  console.error(
    'pyftsubset failed. Install it with `pip install fonttools brotli`, then rerun.',
  );
  throw err;
}

const woff2 = readFileSync(tmp);
unlinkSync(tmp);
const b64 = woff2.toString('base64');

writeFileSync(
  OUT,
  `// GENERATED by scripts/ar-card/subset-marcellus.mjs. Do not hand-edit.
//
// Marcellus Regular, printable-ASCII subset, woff2, base64. Inlined into the
// card landing's single document so the brand face arrives with the markup
// instead of one request and one fallback flash later. SIL Open Font License;
// the license text ships alongside the source TTF at scripts/og/fonts/OFL.txt.
//
// ${woff2.length} bytes of woff2, ${b64.length} bytes of base64.
export const MARCELLUS_WOFF2_BASE64 =
  '${b64}';
`,
  'utf8',
);

console.log(`wrote ${OUT} (${woff2.length}B woff2, ${b64.length}B base64)`);
