#!/usr/bin/env node
// Lighthouse the business pages, mobile preset, and record the scores.
//
// Why: Lighthouse 100s on the business pages are a stated brand feature, and
// the last recorded run was 08-19-26. Since then Zaraz (consent banner), the
// Meta Pixel, the Web Analytics beacon, Astro 7 and the quiet-school rewrap
// all landed. Re-run after anything that touches the business pages' head,
// fonts or scripts.
//
// Usage:
//   node scripts/lighthouse/run.mjs [baseUrl] [outDir]
//   default baseUrl https://birchdesignlab.com, outDir docs/lighthouse/<date>
//
// Runs `npx lighthouse` (fetched on first use) against local Chrome, headless
// with the GPU on (see the GPU-rendering note in the project memory: headless
// otherwise falls back to software rendering and skews timings). Each page is
// run RUNS times and the median performance score is kept, because single
// mobile-throttled runs wobble by several points.
//
// Writes summary.md (a table) and one JSON per page per run.

import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const base = (process.argv[2] ?? 'https://birchdesignlab.com').replace(/\/$/, '');
const day = new Date().toISOString().slice(0, 10);
const outDir = process.argv[3] ?? join('docs', 'lighthouse', day);
const PAGES = ['/', '/services/', '/about/', '/contact/', '/contact/sent/'];
const RUNS = 3;
const CATS = ['performance', 'accessibility', 'best-practices', 'seo'];

mkdirSync(outDir, { recursive: true });
const npx = process.platform === 'win32' ? 'npx.cmd' : 'npx';
const median = (xs) => [...xs].sort((a, b) => a - b)[Math.floor(xs.length / 2)];

const rows = [];
for (const page of PAGES) {
  const scores = Object.fromEntries(CATS.map((c) => [c, []]));
  const metrics = { lcp: [], cls: [], tbt: [] };
  for (let i = 1; i <= RUNS; i++) {
    const slug = page === '/' ? 'home' : page.replace(/^\/|\/$/g, '').replace(/\//g, '-');
    const file = join(outDir, `${slug}-${i}.json`);
    execFileSync(
      npx,
      [
        '-y', 'lighthouse@12', `${base}${page}`,
        '--output=json', `--output-path=${file}`, '--quiet',
        `--only-categories=${CATS.join(',')}`,
        '--chrome-flags=--headless=new --use-angle=d3d11 --enable-gpu',
      ],
      { stdio: ['ignore', 'ignore', 'inherit'], shell: process.platform === 'win32' },
    );
    const r = JSON.parse(readFileSync(file, 'utf8'));
    for (const c of CATS) scores[c].push(Math.round((r.categories[c]?.score ?? 0) * 100));
    metrics.lcp.push(r.audits['largest-contentful-paint']?.numericValue ?? NaN);
    metrics.cls.push(r.audits['cumulative-layout-shift']?.numericValue ?? NaN);
    metrics.tbt.push(r.audits['total-blocking-time']?.numericValue ?? NaN);
    console.log(`${page} run ${i}: perf ${scores.performance.at(-1)}`);
  }
  rows.push({
    page,
    ...Object.fromEntries(CATS.map((c) => [c, median(scores[c])])),
    lcp: Math.round(median(metrics.lcp)),
    cls: median(metrics.cls).toFixed(3),
    tbt: Math.round(median(metrics.tbt)),
    perfRange: `${Math.min(...scores.performance)}-${Math.max(...scores.performance)}`,
  });
}

const md = [
  `# Lighthouse, ${day}`,
  '',
  `Mobile preset, ${base}, median of ${RUNS} runs per page (performance range in brackets). Generated by scripts/lighthouse/run.mjs.`,
  '',
  '| Page | Perf | A11y | Best practices | SEO | LCP ms | CLS | TBT ms |',
  '|---|---|---|---|---|---|---|---|',
  ...rows.map(
    (r) => `| ${r.page} | ${r.performance} (${r.perfRange}) | ${r.accessibility} | ${r['best-practices']} | ${r.seo} | ${r.lcp} | ${r.cls} | ${r.tbt} |`,
  ),
  '',
].join('\n');
writeFileSync(join(outDir, 'summary.md'), md);
console.log('\n' + md);
